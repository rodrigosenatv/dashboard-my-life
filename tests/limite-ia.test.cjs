const test = require("node:test")
const assert = require("node:assert/strict")
const fs = require("node:fs")
const path = require("node:path")
const ler = (nome) => fs.readFileSync(path.join(__dirname, "..", nome), "utf8")

test("API exige chave pessoal e nunca usa fallback global ou quota compartilhada", () => {
  const route = ler("src/app/api/ia/route.ts")
  assert.match(route, /if \(!credencial\) return NextResponse\.json/)
  assert.match(route, /status: 400/)
  assert.match(route, /const chave = typeof corpo\.chave === "string"/)
  assert.doesNotMatch(route, /chaveDaVercel|reservarUsoIACompartilhada|liberarUsoIACompartilhada|ANTHROPIC_API_KEY|SUPABASE_SERVICE_ROLE_KEY/)
  assert.doesNotMatch(route, /export async function GET/)
  assert.ok(route.indexOf("if (!credencial)") < route.indexOf("for await (const pedaco of responder"))
})

test("interface exibe apenas provedores com chave do usuário", () => {
  const ui = ler("src/features/assistente/pagina-assistente.tsx")
  const settings = ler("src/features/configuracoes/chaves-ia.tsx")
  assert.match(ui, /const opcoesIA: Provedor\[\] = ativos/)
  assert.match(ui, /if \(!opcoesIA\.length\)/)
  assert.match(ui, /if \(!provedor \|\| !cred\)/)
  assert.doesNotMatch(ui, /ia-status|status\?\.vercel|fetch\("\/api\/ia"\)/)
  assert.doesNotMatch(settings, /\bvercel\b|fetch\("\/api\/ia"\)/)
  assert.match(settings, /Cada usuário cria sua própria chave/)
})

test("servidor só encaminha chave fornecida na própria requisição", () => {
  const server = ler("src/lib/ia/servidor.ts")
  const route = ler("src/app/api/ia/route.ts")
  assert.doesNotMatch(server, /chaveDaVercel|ANTHROPIC_API_KEY|ANTHROPIC_MODEL/)
  assert.match(server, /export async function\* responder/)
  assert.match(route, /mesmaOrigem/)
  assert.match(route, /getClaims\(\)/)
})
